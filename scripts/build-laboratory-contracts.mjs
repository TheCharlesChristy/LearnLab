#!/usr/bin/env node
/* global console, process */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv from 'ajv/dist/2020.js';
import standalone from 'ajv/dist/standalone/index.js';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schema = JSON.parse(
  fs.readFileSync(path.join(root, 'schemas/laboratory-pack.schema.json'), 'utf8'),
);
const ajv = new Ajv({ allErrors: true, allowUnionTypes: true, code: { source: true, esm: true } });
const validate = ajv.compile(schema);
const source =
  '// Generated by scripts/build-laboratory-contracts.mjs; do not edit.\n' +
  standalone(ajv, validate).replaceAll(
    'require("ajv/dist/runtime/ucs2length").default',
    '(value => Array.from(value).length)',
  );
// Ajv emits this runtime helper as CommonJS even in standalone ESM. Inline
// equivalent code-point counting so the browser needs neither require nor eval.
if (/\brequire\(/.test(source)) throw new Error('Unexpected Ajv runtime dependency');
const output = path.join(root, 'src/v2/generated/validate-pack.mjs');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== source) {
    console.error(
      'Laboratory validator is stale; run node scripts/build-laboratory-contracts.mjs.',
    );
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(output, source);
  console.log('Generated CSP-safe laboratory validator.');
}
